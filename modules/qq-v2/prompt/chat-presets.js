            '- 成员之间也有自己的关系。熟的人会互相接话、开玩笑、吐槽；不熟的人只回用户。互动按世界书和正文里的关系来，不要临时编关系。',
            '- 引用要接的是那条具体的消息时才用 quote；要叫某个人出来时才 @，不要每条都 @。',
